# Commits the result of tools/sync-from-cff.sh to a fixed branch and opens or
# updates one pull request for it. The .github/workflows/cff-sync.yml workflow
# runs this script after the sync; GH_TOKEN must allow pushing the branch and
# editing pull requests.
#
# Environment:
#   TARGET                 Fabric release the sync targeted, such as v59.2.0.
#   CONFLICTS              Number of conflicting files.
#   PROVIDER_MAJOR_CHANGE  true when the release needs a new provider major.
#   REPORT                 Path of the Markdown report from the sync.
#   SYNC_BRANCH            Branch to push. Default: chore/cff-sync.
#   BASE_BRANCH            Branch to merge into. Default: main.

set -euo pipefail

: "${TARGET:?}" "${CONFLICTS:?}" "${PROVIDER_MAJOR_CHANGE:?}" "${REPORT:?}"
SYNC_BRANCH="${SYNC_BRANCH:-chore/cff-sync}"
BASE_BRANCH="${BASE_BRANCH:-main}"
TITLE="chore(modules): sync Cloud Foundation Fabric modules and tooling to ${TARGET}"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}"

BOT_NAME="${GIT_AUTHOR_NAME:-github-actions[bot]}"
BOT_EMAIL="${GIT_AUTHOR_EMAIL:-41898283+github-actions[bot]@users.noreply.github.com}"
# GitHub limits pull request bodies to 65536 characters.
MAX_REPORT_CHARS=50000

gh auth setup-git
git config user.name "${BOT_NAME}"
git config user.email "${BOT_EMAIL}"

git switch --quiet -C "${SYNC_BRANCH}"
git add -A modules tools/cff-sync.bases
# The sync also writes the repository paths that tools/cff-sync.bases lists
# with a slash in the first field, such as the README tooling.
while read -r path; do
  if [[ -e "${path}" ]] || git ls-files --error-unmatch -- "${path}" \
    >/dev/null 2>&1; then
    git add -A -- "${path}"
  fi
done < <(awk '!/^#/ && $1 ~ /\// { print $1 }' tools/cff-sync.bases 2>/dev/null)
if git diff --cached --quiet; then
  echo "The sync changed nothing."
  exit 0
fi
git commit --quiet -m "${TITLE}" -m "Generated by tools/sync-from-cff.sh."

NUMBER="$(gh pr list --head "${SYNC_BRANCH}" --base "${BASE_BRANCH}" \
  --state open --json number --jq '.[0].number // empty')"

# Never overwrite commits that maintainers pushed to the sync branch, such as
# conflict resolutions. Comment on the pull request once per release instead.
if git fetch --quiet origin "${SYNC_BRANCH}" 2>/dev/null; then
  REMOTE_HEAD="$(git rev-parse FETCH_HEAD)"
  git fetch --quiet origin "${BASE_BRANCH}"
  if git log --format='%ae' "FETCH_HEAD..${REMOTE_HEAD}" |
    grep -qvxF "${BOT_EMAIL}"; then
    echo "${SYNC_BRANCH} has maintainer commits; leaving it unchanged."
    MARKER="<!-- cff-sync:${TARGET} -->"
    if [[ -n "${NUMBER}" ]] &&
      ! gh pr view "${NUMBER}" --json comments --jq '.comments[].body' |
      grep -qF "${MARKER}"; then
      gh pr comment "${NUMBER}" --body "$(
        printf '%s\n' "${MARKER}" \
          "Fabric ${TARGET} is available. This branch has maintainer commits," \
          "so the weekly sync left it unchanged. Merge this pull request first," \
          "or rerun \`tools/sync-from-cff.sh --to ${TARGET}\` on the branch."
      )"
    fi
    exit 0
  fi
  if git diff --quiet "${REMOTE_HEAD}" HEAD; then
    echo "${SYNC_BRANCH} already holds this sync."
  else
    git push --quiet --force origin "HEAD:refs/heads/${SYNC_BRANCH}"
  fi
else
  git push --quiet origin "HEAD:refs/heads/${SYNC_BRANCH}"
fi

DRAFT=false
if [[ "${CONFLICTS}" != "0" || "${PROVIDER_MAJOR_CHANGE}" == "true" ]]; then
  DRAFT=true
fi

BODY="$(mktemp)"
trap 'rm -f "${BODY}"' EXIT
{
  echo "## Description"
  echo
  echo "This automated pull request syncs the modules and the repository tooling"
  echo "that track upstream Cloud Foundation Fabric to ${TARGET}. The"
  echo "\`tools/sync-from-cff.sh\` script three-way merged each module and"
  echo "tracked path from its recorded base release, as the"
  echo "\`docs/upstream-sync.md\` guide describes."
  echo
  if [[ "${CONFLICTS}" != "0" ]]; then
    echo "- ${CONFLICTS} files conflict. The branch keeps the local copy of each"
    echo "  one, so a maintainer reruns the script with \`--conflict-style"
    echo "  markers\` on this branch, resolves the conflicts and pushes the"
    echo "  result. The weekly sync then leaves the branch alone."
  fi
  if [[ "${PROVIDER_MAJOR_CHANGE}" == "true" ]]; then
    echo "- The release needs a new google provider major version, so the"
    echo "  Stellar Engine modules, stages and documentation need updates in"
    echo "  this pull request before it can merge."
  fi
  if [[ "${DRAFT}" == "true" ]]; then
    echo "- The pull request stays a draft until it merges cleanly and passes"
    echo "  the checks that \`docs/upstream-sync.md\` lists."
  fi
  echo
  echo "No issue exists for this recurring sync."
  echo
  sed -n '/^## Type of Change/,$p' .github/pull_request_template.md |
    sed '/^## Testing Performed/,$d'
  echo "## Testing Performed"
  echo
  echo "The workflow ran the sync only. A maintainer documents the validation"
  echo "and deployment testing here before the pull request merges."
  echo
  if [[ "$(wc -c <"${REPORT}")" -gt ${MAX_REPORT_CHARS} ]]; then
    head -c "${MAX_REPORT_CHARS}" "${REPORT}" | sed '$d'
    echo
    echo "The report is truncated. Run \`tools/sync-from-cff.sh --dry-run\` for"
    echo "the full report."
  else
    cat "${REPORT}"
  fi
} >"${BODY}"

if [[ -z "${NUMBER}" ]]; then
  args=(--base "${BASE_BRANCH}" --head "${SYNC_BRANCH}" --title "${TITLE}"
    --body-file "${BODY}")
  [[ "${DRAFT}" == "true" ]] && args+=(--draft)
  gh pr create "${args[@]}"
else
  gh pr edit "${NUMBER}" --title "${TITLE}" --body-file "${BODY}"
  if [[ "${DRAFT}" == "true" ]]; then
    # The command fails when the pull request is a draft already.
    gh pr ready "${NUMBER}" --undo || true
  fi
fi
